#!/usr/bin/env python3
"""Generate crates/mnote-app/src/theme/tokens.rs from design/tokens.json.

The design system is the source of truth for colours, type, spacing and sizes.
This script turns its tokens into plain Rust constants so the app needs no JSON
dependency at build or run time.

    python3 tools/gen_theme.py          # rewrite tokens.rs
    python3 tools/gen_theme.py --check  # exit 1 if tokens.rs is out of date (CI)
"""

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "tokens.json"
OUT = ROOT / "crates" / "mnote-app" / "src" / "theme" / "tokens.rs"


RUST_KEYWORDS = {
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "gen", "box", "yield",
}


def ident(name: str) -> str:
    s = re.sub(r"[^0-9a-zA-Z]+", "_", name).strip("_")
    return s + "_" if s in RUST_KEYWORDS else s


def color_u32(value: str) -> str:
    """Return a CSS colour as an 0xRRGGBBAA literal."""
    v = value.strip().lower()
    m = re.fullmatch(r"#([0-9a-f]{6})([0-9a-f]{2})?", v)
    if m:
        return f"0x{m.group(1)}{m.group(2) or 'ff'}"
    m = re.fullmatch(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)", v)
    if m:
        r, g, b = (int(m.group(i)) for i in (1, 2, 3))
        a = round(float(m.group(4) or 1) * 255)
        return f"0x{r:02x}{g:02x}{b:02x}{a:02x}"
    raise ValueError(f"unsupported colour value: {value!r}")


def px(value) -> str:
    if isinstance(value, (int, float)):
        return f"{float(value)}"
    m = re.fullmatch(r"(-?[\d.]+)px", str(value).strip())
    if not m:
        raise ValueError(f"expected a px length, got {value!r}")
    return f"{float(m.group(1))}"


def em(value) -> str:
    if value is None:
        return "0.0"
    m = re.fullmatch(r"(-?[\d.]+)em", str(value).strip())
    if not m:
        raise ValueError(f"expected an em length, got {value!r}")
    return f"{float(m.group(1))}"


def shadow_layers(value: str):
    layers = []
    for part in re.split(r",(?![^(]*\))", value):
        m = re.fullmatch(r"\s*(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(?:(-?[\d.]+)(?:px)?\s+)?(rgba?\([^)]*\)|#[0-9a-fA-F]{6,8})\s*", part)
        if not m:
            raise ValueError(f"unsupported shadow layer: {part!r}")
        x, y, blur, spread, color = m.groups()
        layers.append((x, y, blur, spread or "0", color_u32(color)))
    return layers


def main() -> int:
    tokens = json.loads(SRC.read_text())
    themes = [t["id"] for t in tokens["color"]["themes"]]
    colors = tokens["color"]["tokens"]
    out = []
    w = out.append

    w("// @generated by tools/gen_theme.py from design/tokens.json. Do not edit by hand.")
    w("//! Design tokens from the mNote design system, as plain constants.")
    w("")
    w("/// Every colour token for one theme, as `0xRRGGBBAA`.")
    w("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
    w("pub struct Palette {")
    for c in colors:
        w(f"    /// {c.get('usage', '').strip()}")
        w(f"    pub {ident(c['name'])}: u32,")
    w("}")
    w("")
    w("/// One layer of a box shadow, in px, with an `0xRRGGBBAA` colour.")
    w("#[derive(Debug, Clone, Copy, PartialEq)]")
    w("pub struct ShadowLayer {")
    w("    pub x: f32,")
    w("    pub y: f32,")
    w("    pub blur: f32,")
    w("    pub spread: f32,")
    w("    pub color: u32,")
    w("}")
    w("")
    for theme in themes:
        w(f"/// The `{theme}` theme.")
        w(f"pub const {theme.upper()}: Palette = Palette {{")
        for c in colors:
            v = c["value"]
            value = v.get(theme, v[themes[0]]) if isinstance(v, dict) else v
            w(f"    {ident(c['name'])}: {color_u32(value)},")
        w("};")
        w("")
    for s in tokens.get("shadow", {}).get("tokens", []):
        for theme in themes:
            v = s["value"]
            value = v.get(theme, v[themes[0]]) if isinstance(v, dict) else v
            name = f"{ident(s['name']).upper()}_{theme.upper()}"
            w(f"/// {s.get('usage', '').strip()} ({theme})")
            w(f"pub const {name}: &[ShadowLayer] = &[")
            for x, y, blur, spread, color in shadow_layers(value):
                w(f"    ShadowLayer {{ x: {px(x + 'px')}, y: {px(y + 'px')}, blur: {px(blur + 'px')}, spread: {px(spread + 'px')}, color: {color} }},")
            w("];")
            w("")

    fams = tokens["type"]["families"]
    w("/// Font families: the first family in each design-system stack.")
    w("pub mod family {")
    for key, stack in fams.items():
        first = stack.split(",")[0].strip().strip('"')
        w(f"    pub const {ident(key).upper()}: &str = {json.dumps(first)};")
    w("}")
    w("")
    w("/// Which family a text style uses.")
    w("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
    w("pub enum Family {")
    for key in fams:
        w(f"    {ident(key).capitalize()},")
    w("}")
    w("")
    w("/// A text style: size and line height in px, weight 100 to 900, tracking in em.")
    w("#[derive(Debug, Clone, Copy, PartialEq)]")
    w("pub struct TextStyle {")
    w("    pub family: Family,")
    w("    pub size: f32,")
    w("    pub line_height: f32,")
    w("    pub weight: u16,")
    w("    pub letter_spacing: f32,")
    w("}")
    w("")
    w("pub mod text {")
    w("    use super::{Family, TextStyle};")
    for g in tokens["type"]["groups"]:
        for s in g["styles"]:
            fam = ident(s.get("family", g["family"])).capitalize()
            w(f"    /// {s.get('usage', '').strip()}")
            w(f"    pub const {ident(s['name']).upper()}: TextStyle = TextStyle {{ family: Family::{fam}, size: {px(s['fontSize'])}, line_height: {px(s['lineHeight'])}, weight: {int(s['fontWeight'])}, letter_spacing: {em(s.get('letterSpacing'))} }};")
    w("}")
    w("")
    for fam_key, mod in (("spacing", "space"), ("radius", "radius"), ("size", "size")):
        w(f"/// {fam_key.capitalize()} tokens in px.")
        w(f"pub mod {mod} {{")
        for t in tokens[fam_key]["tokens"]:
            name = ident(t["name"]).upper()
            for prefix in ("SPACE_", "RADIUS_"):
                if name.startswith(prefix):
                    name = name[len(prefix):]
                    if prefix == "SPACE_":
                        name = "S" + name
            w(f"    /// {t.get('usage', '').strip()}")
            w(f"    pub const {name}: f32 = {px(t['value'])};")
        w("}")
        w("")

    text = "\n".join(out).rstrip() + "\n"
    # Format exactly as `cargo fmt` would, so the check and the formatter agree.
    text = subprocess.run(
        ["rustfmt", "--edition", "2024"], input=text, capture_output=True, text=True, check=True
    ).stdout
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 tools/gen_theme.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
